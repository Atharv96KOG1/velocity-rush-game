"""Stamps a version on every game file so browsers always load the latest code.

GitHub Pages lets browsers cache files for 10 minutes, and ES module imports are
cached separately from the page, so after an update players could keep running
old code. This script rewrites index.html with an import map that adds
?v=<hash> to every module in src/ (and to style.css). The hash is computed from
the file contents, so it only changes when the code does.

Run before committing:  python3 stamp.py
"""
import hashlib
import json
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "src")


def content_hash():
    h = hashlib.sha1()
    files = sorted(f for f in os.listdir(SRC) if f.endswith(".js"))
    for name in files + ["../style.css"]:
        with open(os.path.join(SRC, name), "rb") as f:
            h.update(name.encode())
            h.update(f.read())
    return h.hexdigest()[:8], files


def main():
    version, files = content_hash()
    imports = {
        "three": "https://cdn.jsdelivr.net/npm/three@0.169.0/build/three.module.js",
        "three/addons/": "https://cdn.jsdelivr.net/npm/three@0.169.0/examples/jsm/",
    }
    for f in files:
        imports[f"./src/{f}"] = f"./src/{f}?v={version}"
    importmap = json.dumps({"imports": imports}, indent=2)
    html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="version" content="{version}">
<title>Velocity Rush</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Orbitron:wght@500;700;900&family=Rajdhani:wght@500;600;700&display=swap" rel="stylesheet">
<link rel="stylesheet" href="style.css?v={version}">
<!-- Generated by stamp.py: versioned module URLs so updates are never served from a stale cache. -->
<script type="importmap">
{importmap}
</script>
</head>
<body>
<div id="game"></div>
<div id="hud"></div>
<div id="ui"></div>
<div id="loading">LOADING…</div>
<script type="module" src="src/main.js?v={version}"></script>
</body>
</html>
"""
    with open(os.path.join(ROOT, "index.html"), "w") as f:
        f.write(html)
    print(f"index.html stamped with version {version} ({len(files)} modules)")


if __name__ == "__main__":
    main()
